#!/bin/sh
#初始化环境变量：
begin_date="${p_start_dt}"
end_date="${p_end_dt}"
P_BATCH_DT=$begin_date
echo  $P_BATCH_DT
while [ $P_BATCH_DT -lt $end_date ]; 
do
    source /home/dolphinscheduler/hadoop_env
    inceptor_beeline()
    {
        beeline -u ${hive_jdbc} -n ${hive_username} -p ${hive_password}   -e "$1"
    }
    
    inceptor_beeline "
    -- *************事件
    -- ** 描述: DWD_EVT_SCR_CHANGE_BUSIN_PTD
    -- ** 创建者 : vhhv
    -- ** 创建日期: 20230621
    -- ** 目标表：DWDXDAY.DWD_EVT_SCR_CHANGE_BUSIN_PTD             证券转换业务
    -- ** 源表：  ODS_XDAY_HSFA.ODS_HSFA_TQSK_PTD     清算库
    -- **************************************************************************
    
set hive.strict.checks.type.safety=false;
    set mapred.max.split.size=256000000;
    set mapred.min.split.size.per.node=100000000;
    set mapred.min.split.size.per.rack=100000000;
    set hive.merge.mapredfiles=true;
    set hive.merge.mapfiles=true;
    set hive.merge.smallfiles.avgsize=16000000;
    set hive.merge.size.per.task=256000000;
    set hive.exec.reducers.bytes.per.reducer=10240000000; 
    set mapreduce.job.reduces=2;
    
    INSERT OVERWRITE TABLE DWDXDAY.DWD_EVT_SCR_CHANGE_BUSIN_PTD PARTITION ( P_DT='${P_BATCH_DT}')
    SELECT
        CAST(A1.L_ZTBH AS STRING) AS SFAC_NO -- 账套编号
        ,A10.SFAC_NUM AS SFAC_NUM -- 账套编码
        ,A1.D_RQ AS TRAN_DATE -- 交易日期
        ,A10.PROD_CODE AS PROD_CODE -- 产品代码
        ,A5.STD_DICT_CLS_CD_VAL AS BUSIN_CATG -- 业务类别
        ,A6.STD_DICT_CLS_CD_VAL AS BUSIN_DETAIL_CATG -- 业务明细类别
        ,CASE WHEN A1.L_YWLB IN (1018,1053,1054,1108,1114,1219,1241,1243,1250,1253) THEN A11.SCR_NUM ELSE '' END AS OUT_SCR_NUM -- 转出证券编码
        ,CASE WHEN A1.L_YWLB IN (1018,1053,1054,1108,1114,1219,1241,1243,1250,1253) THEN CAST(A1.L_ZQNM AS STRING) ELSE '' END AS OUT_SCR_INCD -- 转出证券内码
        ,CASE WHEN A1.L_YWLB IN (1018,1053,1054,1108,1114,1219,1241,1243,1250,1253) THEN A1.VC_ZQDM ELSE '' END AS OUT_SYMBOL -- 转出证券代码
        ,CASE WHEN A1.L_YWLB IN (1018,1053,1054,1108,1114,1219,1241,1243,1250,1253) THEN A11.SCR_TYPE ELSE '' END AS OUT_SCR_VAR -- 转出证券品种
        ,CASE WHEN A1.L_YWLB IN (1018,1053,1054,1108,1114,1219,1241,1243,1250,1253) THEN A11.TRAN_MKT_CODE ELSE '' END AS OUT_TRAN_MKT -- 转出交易市场
        ,CASE WHEN A1.L_YWLB IN (1018,1053,1054,1108,1114,1219,1241,1243,1250,1253) THEN A1.VC_JSBZ ELSE '' END AS OUT_TRAN_CRRC -- 转出交易币种
        ,CASE WHEN A1.L_YWLB IN (1018,1053,1054,1108,1114,1219,1241,1243,1250,1253) THEN CAST(A1.L_TQBZ AS STRING) ELSE '' END AS OUT_SCR_TRAN_PROP -- 转出证券交易属性
        ,'' AS OUT_SCR_SUE_MODE -- 转出证券发行方式
        ,CASE WHEN A1.L_YWLB IN (1018,1053,1054,1108,1114,1219,1241,1243,1250,1253) THEN NVL(A7.STD_DICT_CLS_CD_VAL,'2') ELSE '' END AS OUT_INV_CATG -- 转出投资分类
        ,A1.L_MCSL AS OUT_QTY -- 转出数量
        ,CASE WHEN A1.L_YWLB = 1108 THEN A1.EN_MCCB ELSE A1.EN_MCJE END AS OUT_AMT -- 转出金额
        ,0 AS OUT_VAL_APPRE -- 转出估值增值
        ,0 AS OUT_PREM -- 转出溢折价
        ,0 AS OUT_DIVD -- 转出股利
        ,A1.EN_MCLX AS OUT_INTR -- 转出利息
        ,'' AS IN_SFAC_NUM -- 转入账套编码
        ,'' AS IN_SFAC_NO -- 转入账套编号
        ,'' AS IN_PROD_CODE -- 转入产品代码
        ,CASE WHEN A1.L_YWLB IN(1019,1051,1052,1115,1118,1220,1240,1242,1251,1252) THEN A11.SCR_NUM ELSE '' END AS IN_SCR_NUM  -- 转入证券编码
        ,CASE WHEN A1.L_YWLB IN(1019,1051,1052,1115,1118,1220,1240,1242,1251,1252) THEN CAST(A1.L_ZQNM AS STRING) ELSE '' END AS IN_SCR_INCD -- 转入证券内码
        ,CASE WHEN A1.L_YWLB IN(1019,1051,1052,1115,1118,1220,1240,1242,1251,1252) THEN A1.VC_ZQDM ELSE '' END AS IN_SYMBOL  -- 转入证券代码
        ,CASE WHEN A1.L_YWLB IN(1019,1051,1052,1115,1118,1220,1240,1242,1251,1252) THEN A11.SCR_TYPE ELSE '' END AS IN_SCR_VAR -- 转入证券品种
        ,CASE WHEN A1.L_YWLB IN(1019,1051,1052,1115,1118,1220,1240,1242,1251,1252) THEN A1.VC_JSBZ ELSE '' END AS IN_TRAN_CRRC -- 转入交易币种
        ,CASE WHEN A1.L_YWLB IN(1019,1051,1052,1115,1118,1220,1240,1242,1251,1252) THEN A11.TRAN_MKT_CODE ELSE '' END AS IN_TRAN_MKT -- 转入交易市场
        ,CASE WHEN A1.L_YWLB IN(1019,1051,1052,1115,1118,1220,1240,1242,1251,1252) THEN CAST(A1.L_TQBZ AS STRING) ELSE '' END AS IN_TRAN_PROP -- 转入交易属性
        ,'' AS IN_SCR_SUE_MODE -- 转入证券发行方式
        ,CASE WHEN A1.L_YWLB IN(1019,1051,1052,1115,1118,1220,1240,1242,1251,1252) THEN NVL(A7.STD_DICT_CLS_CD_VAL,'2') ELSE '' END AS IN_INV_CATG -- 转入投资分类
        ,A1.L_MRSL AS IN_DEAL_QTY -- 转入成交数量
        ,A1.EN_MRJE AS IN_DEAL_AMT -- 转入成交金额
        ,0 AS IN_VAL_APPRE -- 转入估值增值
        ,0 AS IN_PREM -- 转入溢折价
        ,0 AS IN_DIVD -- 转入股利
        ,A1.EN_MRLX AS IN_INTR -- 转入利息
        ,A1.VC_XWDM AS TRAN_CHNL -- 交易渠道
        ,A1.VC_GDDM AS TRAN_ACCT -- 交易账户
        ,A1.VC_ZHDM AS CPTL_ACCT -- 资金账户
        ,(A1.EN_MRSXF + A1.EN_MCSXF) AS CHANGEFEE -- 转换费用
        ,(A1.EN_MRQTFY + A1.EN_MCQTFY) AS OTH_FEE -- 其他费用
        ,CAST(A1.L_BH AS STRING) AS DEAL_NO -- 成交编号
        ,CAST(A1.L_GLBH AS STRING) AS RELA_NO -- 关联编号
        ,'HSFA' AS SSYS -- 源系统
        ,'ODS_HSFA_TQSK_PTD ' AS SOURCE_TAB -- 源表
        ,FROM_UNIXTIME(UNIX_TIMESTAMP(CURRENT_TIMESTAMP()),'yyyy-MM-dd HH:mm:ss') AS LD_TIME -- 加载时间
        ,FROM_UNIXTIME(UNIX_TIMESTAMP(CURRENT_TIMESTAMP()),'yyyy-MM-dd HH:mm:ss') AS MODIFY_TIME -- 修改时间
    FROM ODS_XDAY_HSFA.ODS_HSFA_TQSK_PTD A1 -- 清算库
    LEFT JOIN DWDXDAY.DWD_PROD_SFAC_NUM_MAPP_PFD A10  -- 帐套编码映射
    ON CAST(A1.L_ZTBH AS STRING)=A10.SFAC_INCD AND A10.P_DT = DATE_ADD(FROM_UNIXTIME(UNIX_TIMESTAMP(CURRENT_TIMESTAMP()),'yyyyMMdd'),-1)
    LEFT JOIN 
        (SELECT
            C1.SCR_NUM  --证券编码
            ,C1.TRAN_MKT_CODE  --交易市场
            ,C2.SCR_INCD  --证券内码
            ,C3.SCR_PRI_CATG_CODE AS SCR_TYPE  --证券类别代码(证券类型)
            ,C3.SCR_SCD_CATG_CODE AS SCR_DETAIL_TYPE  --分类代码(证券明细类型)
         FROM DWDXDAY.DWD_SCR_SCR_BASIC_INFO_PFD C1 --证券基本信息
         LEFT JOIN DWDXDAY.DWD_SCR_SCR_NUM_MAPP_PFD C2  -- 证券编码映射
         ON C1.SCR_NUM=C2.SCR_NUM AND C2.SSYS= 'HSFA' AND C2.VALID_FLAG=1 AND C2.P_DT = DATE_ADD(FROM_UNIXTIME(UNIX_TIMESTAMP(CURRENT_TIMESTAMP()),'yyyyMMdd'),-1)
         LEFT JOIN DWDXDAY.DWD_SCR_SCR_CATG_INFO_PFD C3  --证券分类信息
         ON C1.SCR_NUM=C3.SCR_NUM AND C3.CATG_CALIBRE_CODE='HSFA_SCR_CATG_CODE' AND C3.P_DT = DATE_ADD(FROM_UNIXTIME(UNIX_TIMESTAMP(CURRENT_TIMESTAMP()),'yyyyMMdd'),-1)
         WHERE C1.P_DT = DATE_ADD(FROM_UNIXTIME(UNIX_TIMESTAMP(CURRENT_TIMESTAMP()),'yyyyMMdd'),-1)
        ) A11
    ON CAST(A1.L_ZQNM AS STRING)=A11.SCR_INCD
    LEFT JOIN DWDXDAY.DWD_CMM_STD_DICT_CDVAL_MAP A5
    ON A5.SSYS= 'HSFA' AND A5.SRC_DICT_CLS_CD= 'L_YWLB' AND CAST(A1.L_YWLB AS STRING) = A5.SRC_DICT_CLS_CDVAL  AND A5.VALID_FLAG='1'
    LEFT JOIN DWDXDAY.DWD_CMM_STD_DICT_CDVAL_MAP A6
    ON A6.SSYS= 'HSFA' AND A6.SRC_DICT_CLS_CD= 'L_YWLBMX' AND CAST(A1.L_YWLBMX AS STRING) = A6.SRC_DICT_CLS_CDVAL  AND A6.VALID_FLAG='1'
    LEFT JOIN DWDXDAY.DWD_CMM_STD_DICT_CDVAL_MAP A7
    ON A7.SSYS= 'HSFA' AND A7.SRC_DICT_CLS_CD= 'L_TZLX' AND CAST(A1.L_TZLX AS STRING) = A7.SRC_DICT_CLS_CDVAL  AND A7.VALID_FLAG='1'
    WHERE A1.P_DT = '${P_BATCH_DT}' AND A1.L_YWLB IN(1018,1019,1051,1052,1053,1054,1108,1114,1219,1241,1243,1250,1253,1115,1118,1220,1240,1242,1251,1252)
    ;
    "
    P_BATCH_DT=$(date -d "$P_BATCH_DT+1days" +%Y%m%d)
done

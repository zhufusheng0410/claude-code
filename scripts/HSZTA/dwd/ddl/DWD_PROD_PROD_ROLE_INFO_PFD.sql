CREATE TABLE  DWDXDAY.DWD_PROD_PROD_ROLE_INFO_PFD (
   PROD_NUM  STRING COMMENT '产品编码', 
   PTY_NUM  STRING COMMENT '主体编码', 
   PROD_CODE  STRING COMMENT '产品代码', 
   ROLE_TYPE_CODE  STRING COMMENT '角色类型代码', 
   PTY_NAME  STRING COMMENT '主体名称', 
   ST_DATE  STRING COMMENT '开始日期', 
   END_DATE  STRING COMMENT '结束日期', 
   VALID_FLAG  STRING COMMENT '有效标志', 
   SSYS  STRING COMMENT '源系统', 
   SRC_TAB  STRING COMMENT '源表', 
   LD_TIME  STRING COMMENT '加载时间', 
   MODIFY_TIME  STRING COMMENT '修改时间'
)
COMMENT '产品角色信息'
PARTITIONED BY ( P_DT  STRING)  
ROW FORMAT DELIMITED FIELDS TERMINATED BY '\t' NULL DEFINED AS '';
